/// Lista de bancos brasileiros participantes do STR (Sistema de Transferência de Reservas)
/// Baseado na Lista de Participantes do STR - Portal de Dados Abertos do Banco Central do Brasil
/// 
/// Regras:
/// - Códigos sempre com 3 dígitos (completar com zeros à esquerda se necessário)
/// - Exemplo: "96" deve ser registrado como "096"
/// - Instituições com código "N/A" ficam de fora da lista
library;

class BrazilianBank {
  final String code; // Código de 3 dígitos
  final String name; // Nome completo do banco

  const BrazilianBank({
    required this.code,
    required this.name,
  });

  /// Retorna a representação para exibição: "001 - Banco do Brasil S.A."
  String get displayName => '$code - $name';

  /// Remove acentos de uma string para normalização na busca
  static String _removeAccents(String text) {
    const Map<String, String> accents = {
      'á': 'a', 'à': 'a', 'ã': 'a', 'â': 'a', 'ä': 'a',
      'é': 'e', 'è': 'e', 'ê': 'e', 'ë': 'e',
      'í': 'i', 'ì': 'i', 'î': 'i', 'ï': 'i',
      'ó': 'o', 'ò': 'o', 'õ': 'o', 'ô': 'o', 'ö': 'o',
      'ú': 'u', 'ù': 'u', 'û': 'u', 'ü': 'u',
      'ç': 'c',
      'Á': 'A', 'À': 'A', 'Ã': 'A', 'Â': 'A', 'Ä': 'A',
      'É': 'E', 'È': 'E', 'Ê': 'E', 'Ë': 'E',
      'Í': 'I', 'Ì': 'I', 'Î': 'I', 'Ï': 'I',
      'Ó': 'O', 'Ò': 'O', 'Õ': 'O', 'Ô': 'O', 'Ö': 'O',
      'Ú': 'U', 'Ù': 'U', 'Û': 'U', 'Ü': 'U',
      'Ç': 'C',
    };
    
    return text.splitMapJoin(
      RegExp(r'[áàãâäéèêëíìîïóòõôöúùûüçÁÀÃÂÄÉÈÊËÍÌÎÏÓÒÕÔÖÚÙÛÜÇ]'),
      onMatch: (match) => accents[match.group(0)] ?? match.group(0)!,
      onNonMatch: (nonMatch) => nonMatch,
    );
  }

  /// Busca bancos por código ou nome (case-insensitive e sem acentos)
  static List<BrazilianBank> searchBanks(String query, List<BrazilianBank> allBanks) {
    if (query.isEmpty) return allBanks;
    
    final normalizedQuery = _removeAccents(query.toLowerCase().trim());
    return allBanks.where((bank) {
      final normalizedCode = _removeAccents(bank.code.toLowerCase());
      final normalizedName = _removeAccents(bank.name.toLowerCase());
      return normalizedCode.contains(normalizedQuery) || 
             normalizedName.contains(normalizedQuery);
    }).toList();
  }
}

